-- deploy/sql/postgresql-schema.sql — for DBA review. Eminova.Host creates this automatically (EnsureCreated);
-- run manually only when the application login is not allowed to create objects.
CREATE ROLE eminova_app LOGIN PASSWORD '<SECRET>';
CREATE DATABASE eminova OWNER eminova_app ENCODING 'UTF8';
\c eminova
CREATE TABLE eminova_state (
  "TenantId"   varchar(64)  NOT NULL,
  "UserId"     varchar(256) NOT NULL,
  "Json"       text         NOT NULL,
  "Version"    integer      NOT NULL DEFAULT 0,
  "UpdatedUtc" timestamp with time zone NOT NULL,
  CONSTRAINT "PK_eminova_state" PRIMARY KEY ("TenantId","UserId"));
CREATE TABLE eminova_audit (
  "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "TenantId" varchar(64) NOT NULL, "UserId" varchar(256) NOT NULL,
  "Action" varchar(64) NOT NULL, "Detail" varchar(1024) NOT NULL, "AtUtc" timestamp with time zone NOT NULL);
CREATE INDEX "IX_eminova_audit_TenantId_AtUtc" ON eminova_audit ("TenantId","AtUtc");
CREATE TABLE eminova_import (
  "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "TenantId" varchar(64) NOT NULL, "UserId" varchar(256) NOT NULL, "Entity" varchar(64) NOT NULL,
  "FileName" varchar(260) NOT NULL, "RowsRead" integer NOT NULL, "Added" integer NOT NULL, "Updated" integer NOT NULL,
  "Skipped" integer NOT NULL, "Warnings" varchar(4000) NOT NULL, "AtUtc" timestamp with time zone NOT NULL);
CREATE INDEX "IX_eminova_import_TenantId_AtUtc" ON eminova_import ("TenantId","AtUtc");
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO eminova_app;
